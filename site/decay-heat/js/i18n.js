  let lang = 'en';
  const missed = [];

  function L(key) {
    const e = T[key];
    if (!e) {
      if (missed.indexOf(key) < 0) missed.push(key);
      return key;
    }
    let v = lang === 'fr' && e[1] !== undefined ? e[1] : e[0];
    if (arguments.length > 1 && typeof v === 'string') {
      for (let i = 1; i < arguments.length; i++) v = v.split('{' + (i - 1) + '}').join(arguments[i]);
    }
    return v;
  }

